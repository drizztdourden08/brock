/* @layer tooling-scripts @kind logic */
import { existsSync, readFileSync } from 'node:fs';
import { join } from 'node:path';
import { MANAGED_FILES } from './templates.mjs';

const MANAGED_MARK = 'managed: generated by brock sync';

const KEPT_TARGETS = new Set(MANAGED_FILES.filter(({ keepHandWritten }) => keepHandWritten).map(({ target }) => target));

const isHandWritten = (rootDir, path) => {
  const file = join(rootDir, path);
  return KEPT_TARGETS.has(path) && existsSync(file) && !readFileSync(file, 'utf8').includes(MANAGED_MARK);
};

/**
 * @param {string} rootDir the app folder
 * @param {{ path: string, content: string | null }[]} files the rendered managed files
 * @returns {{ path: string, content: string | null }[]} the files, minus the ones the app wrote itself
 */
const withoutHandWritten = (rootDir, files) => files.filter(({ path }) => !isHandWritten(rootDir, path));

export { withoutHandWritten };

/* @layer tooling-scripts @kind logic */
import { specifierFor } from './resolve.mjs';

const HEADER = '// generated by brock sync, do not edit';

/**
 * @type {Record<'main' | 'preload' | 'renderer', { type: string, from: string, name: string } >}
 */
const SIDES = {
  main: { type: 'MainModule', from: '@drizztdourden08/brock-electron/main', name: 'mainModules' },
  preload: { type: 'PreloadNamespace', from: '@drizztdourden08/brock-electron/preload', name: 'preloadNamespaces' },
  renderer: { type: 'RendererModule', from: '@drizztdourden08/brock-react', name: 'rendererModules' },
};

const identifierOf = (id, side) => {
  const camel = id.replace(/[^a-zA-Z0-9]+(.)?/g, (_, c) => (c ? c.toUpperCase() : ''));
  return `${camel}${side[0].toUpperCase()}${side.slice(1)}`;
};

/**
 * @param {'main' | 'preload' | 'renderer'} side
 * @param {{ packageName: string, exports: unknown, manifest: { id: string, main?: string, preload?: string, renderer?: string}}[]} modules
 * @returns {string}
 */
const renderSide = (side, modules) => {
  const { type, from, name } = SIDES[side];
  const entries = modules
    .filter((m) => m.manifest[side])
    .map((m) => ({ ident: identifierOf(m.manifest.id, side), spec: specifierFor(m.packageName, m.exports, m.manifest[side]) }));
  const imports = entries.map((e) => `import ${e.ident} from '${e.spec}';`);
  const list = entries.length ? `[\n${entries.map((e) => `  ${e.ident},`).join('\n')}\n]` : '[]';
  return [
    HEADER,
    `import type { ${type} } from '${from}';`,
    ...imports,
    '',
    `const ${name}: ${type}[] = ${list};`,
    '',
    `export { ${name} };`,
    '',
  ].join('\n');
};

/**
 * @param {{ brockVersion: string, modules: { packageName: string, version: string, manifest: { id: string}}[], generatedAt: string }} input
 */
const renderManifest = ({ brockVersion, modules, generatedAt }) =>
  `${JSON.stringify(
    {
      brock: brockVersion,
      generatedAt,
      modules: modules.map((m) => ({ id: m.manifest.id, package: m.packageName, version: m.version })),
    },
    null,
    2,
  )}\n`;

/**
 * @param {{ brockVersion: string, modules: any[], generatedAt: string}} input
 * @returns {{ path: string, content: string } []}
 */
const renderBrockDir = (input) => [
  { path: '.brock/modules.main.ts', content: renderSide('main', input.modules) },
  { path: '.brock/modules.preload.ts', content: renderSide('preload', input.modules) },
  { path: '.brock/modules.renderer.ts', content: renderSide('renderer', input.modules) },
  { path: '.brock/manifest.json', content: renderManifest(input) },
];

export { renderBrockDir };

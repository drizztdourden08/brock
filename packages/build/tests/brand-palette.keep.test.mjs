/* @layer tooling-scripts @kind test */
import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { afterEach, describe, expect, it } from 'vitest';
import { renderPaletteFile } from '../src/tessera/render-palette.mjs';
import { collectMigrations, runMigrations, selectMigrations } from '../src/upgrade/index.mjs';

const REPO_ROOT = join(import.meta.dirname, '../../..');
const HEADER = '/* generated by brock sync from product.icons.brand, do not edit */\n';

const made = [];

afterEach(() => {
  for (const dir of made.splice(0)) rmSync(dir, { recursive: true, force: true });
});

const write = (root) => ([file, text]) => {
  const target = join(root, file);
  mkdirSync(dirname(target), { recursive: true });
  writeFileSync(target, text);
};

const tree = (files) => {
  const root = mkdtempSync(join(tmpdir(), 'brock-palette-import-'));
  made.push(root);
  Object.entries(files).forEach(write(root));
  return root;
};

const paletteOf = (brand) => renderPaletteFile(REPO_ROOT, { product: { icons: brand ? { brand } : {} } })[0];

describe('.brock/palette.css', () => {
  it('imports the palette of the product brand alone', () => {
    expect(paletteOf('brock')).toEqual({ path: '.brock/palette.css', content: `${HEADER}@import url('@drizztdourden08/tessera/palettes/brock.css');\n` });
  });

  it('imports nothing without a brand, or for a brand Tessera has no palette for', () => {
    expect(paletteOf(null).content).toBe(HEADER);
    expect(paletteOf('no-such-brand').content).toBe(HEADER);
  });
});

const only = () => selectMigrations(collectMigrations([]), { from: '0.35.0', to: null }).filter((m) => m.file.endsWith('brand-palette-import.mjs'));

const ENTRY = "/* @layer renderer-app @kind entry */\nimport '@drizztdourden08/tessera/tokens.css';\nimport './theme.css';\n";

describe('brand-palette-import migration (0.36.0)', () => {
  it('imports the palette right after Tessera tokens, once', async () => {
    const root = tree({ 'package.json': '{"name":"x"}', 'src/main.tsx': ENTRY });
    expect((await runMigrations(root, only())).applied[0].touched).toEqual(['src/main.tsx']);
    expect(readFileSync(join(root, 'src/main.tsx'), 'utf8')).toBe(
      "/* @layer renderer-app @kind entry */\nimport '@drizztdourden08/tessera/tokens.css';\nimport '../.brock/palette.css';\nimport './theme.css';\n",
    );
    expect((await runMigrations(root, only())).applied[0].touched).toEqual([]);
  });

  it('keeps CRLF line ends and falls back to the header line', async () => {
    const root = tree({ 'src/main.tsx': "/* @layer renderer-app @kind entry */\r\nimport { App } from './App';\r\n" });
    await runMigrations(root, only());
    expect(readFileSync(join(root, 'src/main.tsx'), 'utf8')).toBe("/* @layer renderer-app @kind entry */\r\nimport '../.brock/palette.css';\r\nimport { App } from './App';\r\n");
  });

  it('leaves a to-do when the renderer entry is elsewhere', async () => {
    const root = tree({ 'src/index.tsx': ENTRY });
    const result = await runMigrations(root, only());
    expect(result.applied[0].touched).toEqual([]);
    expect(result.todos).toEqual([expect.objectContaining({ file: 'src/main.tsx', message: expect.stringContaining('.brock/palette.css') })]);
  });
});

/* @layer tooling-scripts @kind test */
import { afterEach, describe, expect, it } from 'vitest';
import { checkLocales } from '../src/i18n/check-locales.mjs';
import { electronLanguages } from '../src/i18n/electron-languages.mjs';
import { messageArgs } from '../src/i18n/message-args.mjs';
import { renderI18nFiles } from '../src/i18n/render-i18n.mjs';
import { renderMessagesType } from '../src/i18n/render-messages-type.mjs';
import { scanLocales } from '../src/i18n/scan-locales.mjs';
import { appDirs } from './app-dir-harness.mjs';

const { appDir, cleanUp } = appDirs('brock-i18n-');

afterEach(cleanUp);

const EN = JSON.stringify({ 'home.title': 'Home', 'items.count': '{count, plural, one {# item} other {# items}}', 'who': '{gender, select, female {She} male {He} other {They}} joined at {at, date, short}', 'help': 'Read <link>the {name}</link> and {names, list}' });
const FR = JSON.stringify({ 'home.title': 'Accueil' });

const files = (dir) => Object.fromEntries(renderI18nFiles(dir).map((file) => [file.path, file.content]));

describe('K1 messageArgs', { tags: ['critical'] }, () => {
  it('reads argument kinds, select options and tags from the message', () => {
    const found = messageArgs("It''s {n, plural, =0 {none} other {# of {who}}} '{raw}' <b>x</b>{p, number, percent}{g, select, a {A} other {B}}");
    expect([...found.args].map(([name, use]) => `${name}:${use.kind}`)).toEqual(['who:arg', 'n:number', 'p:number', 'g:select']);
    expect([...found.tags]).toEqual(['b']);
  });

  it('throws on a message that does not parse', () => {
    expect(() => messageArgs('{open')).toThrow();
    expect(() => messageArgs('{n, plural, one {x}')).toThrow();
    expect(() => messageArgs('{a, bogus}')).toThrow();
  });
});

describe('K1 renderMessagesType', { tags: ['critical'] }, () => {
  it('augments Messages with one typed member per base key and lists the tags', () => {
    const dir = appDir({ 'src/locales/en/app.json': EN, 'src/locales/fr/app.json': FR });
    expect(files(dir)['.brock/messages.type.ts']).toBe([
      '// generated by brock sync, do not edit',
      "declare module '@drizztdourden08/brock-core/augment' {",
      '  interface Messages {',
      "    'app:home.title': Record<never, never>;",
      "    'app:items.count': { count: number };",
      "    'app:who': { gender: 'female' | 'male' | (string & {}); at: Date | number };",
      "    'app:help': { name: string | number; names: readonly string[] };",
      '  }',
      '}',
      '',
      'type AppMessageTags = {',
      "  'app:help': 'link';",
      '};',
      '',
      'export type { AppMessageTags };',
      '',
    ].join('\n'));
  });

  it('writes an empty augmentation for an app with no locales', () => {
    expect(renderMessagesType([])).toContain('interface Messages {}');
    expect(files(appDir({}))['.brock/messages.type.ts']).toContain('interface Messages {}');
  });
});

describe('K1 renderI18nFiles', { tags: ['critical'] }, () => {
  it('bundles the base, makes one lazy chunk per other tag and keeps main namespaces apart', () => {
    const dir = appDir({
      'src/locales/en/app.json': EN,
      'src/locales/en/app-main.json': '{"tray.show":"Show"}',
      'src/locales/fr/app.json': FR,
      'src/locales/fr/app-main.json': '{"tray.show":"Afficher"}',
      'src/locales/de/app.json': '{}',
      'brock.config.ts': "export default { product: { moduleOptions: { i18n: { draft: ['de'] } } } };\n",
    });
    const out = files(dir);
    expect(Object.keys(out).sort()).toEqual(['.brock/locales.main.ts', '.brock/locales.ts', '.brock/locales/fr.ts', '.brock/messages.type.ts']);
    expect(out['.brock/locales.ts']).toContain("import app_en_app from '../src/locales/en/app.json';");
    expect(out['.brock/locales.ts']).toContain("'fr': () => import('./locales/fr'),");
    expect(out['.brock/locales.ts']).toContain("tags: ['en', 'fr'],");
    expect(out['.brock/locales.ts']).not.toContain('app-main');
    expect(out['.brock/locales/fr.ts']).toContain("import app_fr_app from '../../src/locales/fr/app.json';");
    expect(out['.brock/locales/fr.ts']).not.toContain('main');
    expect(out['.brock/locales.main.ts']).toContain("{ locale: 'en', namespace: 'app-main', kind: 'app', messages: app_en_app_main },");
    expect(out['.brock/locales.main.ts']).toContain("'fr': async () => [");
    expect(out['.brock/locales.ts']).not.toContain("'de'");
  });

  it('types the keys of package tables once, and leaves their base out of the bundle', () => {
    const dir = appDir({
      'package.json': '{"dependencies":{"pkg-x":"1.0.0"}}',
      'node_modules/pkg-x/package.json': '{"name":"pkg-x","brock":{"locales":"./src/locales"}}',
      'node_modules/pkg-x/src/locales/en/pkg-x.json': '{"menu.open":"Open","menu.close":"Close"}',
      'src/locales/en/app.json': '{"home.title":"Home"}',
      'src/locales/en/pkg-x.json': '{"menu.open":"Open it"}',
    });
    const out = files(dir);
    const typed = out['.brock/messages.type.ts'];
    expect(typed).toContain("'pkg-x:menu.close': Record<never, never>;");
    expect(typed).toContain("'app:home.title': Record<never, never>;");
    expect(typed.split("'pkg-x:menu.open'").length).toBe(2);
    expect(out['.brock/locales.ts']).not.toContain('node_modules');
  });

  it('removes the chunk of a language whose folder is gone', () => {
    const dir = appDir({ 'src/locales/en/app.json': EN, '.brock/locales/it.ts': 'old\n' });
    expect(renderI18nFiles(dir).find((file) => file.path === '.brock/locales/it.ts')?.content).toBeNull();
  });

  it('trims electron languages to the shipped tags plus en-US', () => {
    expect(electronLanguages(appDir({}))).toEqual(['en-US']);
    expect(electronLanguages(appDir({ 'src/locales/en/a.json': '{}', 'src/locales/fr-CA/a.json': '{}' }))).toEqual(['en-US', 'fr-CA']);
    expect(scanLocales(appDir({})).offered).toEqual(['en']);
  });
});

describe('K1 checkLocales', { tags: ['critical'] }, () => {
  it('reports bad tags, namespaces, messages, keys outside the base and a second language without the module', () => {
    const dir = appDir({
      'src/locales/en/app.json': '{"a":"A"}',
      'src/locales/fr/app.json': '{"a":"{open","extra":"x"}',
      'src/locales/fr/Bad_Name.json': '{}',
      'src/locales/english/app.json': '{}',
      'src/locales/es/app.json': '{"a":1}',
    });
    const findings = checkLocales(dir).join('\n');
    expect(findings).toContain('src/locales/english: not a BCP 47 language tag');
    expect(findings).toContain('"Bad_Name" is not a kebab-case namespace');
    expect(findings).toContain('src/locales/fr/app.json: "a" does not parse');
    expect(findings).toContain('"extra" is not in the base en file');
    expect(findings).toContain('src/locales/es/app.json: "a" is not a string');
    expect(findings).toContain('ship without the i18n module; run brock add i18n');
  });

  it('accepts a clean app with the module installed', () => {
    const dir = appDir({ 'src/locales/en/app.json': EN, 'src/locales/fr/app.json': FR, 'package.json': '{"dependencies":{"@drizztdourden08/brock-i18n":"1.0.0"}}' });
    expect(checkLocales(dir)).toEqual([]);
  });
});

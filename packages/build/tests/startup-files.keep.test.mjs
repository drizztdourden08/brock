/* @layer tooling-scripts @kind test */
import { afterEach, describe, expect, it } from 'vitest';
import { migration } from '../migrations/0.80.0/startup-prompts.mjs';
import { SYNC_INPUTS } from '../src/freshness/freshness.constants.mjs';
import { checkStartup } from '../src/startup/check-startup.mjs';
import { renderStartup, renderStartupFiles } from '../src/startup/render-startup.mjs';
import { appDirs } from './app-dir-harness.mjs';

const MAIN = [
  "import { BrockApp } from '@drizztdourden08/brock-react';",
  "import { screenTree } from '../.brock/screens';",
  "import { appTours } from '../.brock/tours';",
  '',
  'createRoot(root).render(',
  '  <StrictMode>',
  '    <BrockApp<AppSettings>',
  '      product={product}',
  '      tours={appTours}',
  '    />',
  '  </StrictMode>,',
  ');',
  '',
].join('\n');

const { appDir, cleanUp } = appDirs('brock-startup-');

afterEach(cleanUp);

describe('renderStartup', () => {
  it('imports a prompt whose order is not a literal, whole', () => {
    expect(renderStartup([{ id: 'pick-version', path: 'src/startup/pick-version.prompt.ts' }])).toBe([
      '// generated by brock sync, do not edit',
      "import { startupPromptsFromFiles } from '@drizztdourden08/brock-react';",
      "import pickVersionPrompt from '../src/startup/pick-version.prompt';",
      '',
      'const appStartupPrompts = startupPromptsFromFiles([',
      "  { id: 'pick-version', prompt: pickVersionPrompt },",
      ']);',
      '',
      'export { appStartupPrompts };',
      '',
    ].join('\n'));
  });

  it('lists a prompt with a literal or no order by that alone and loads the file when it runs', () => {
    const read = (source) => renderStartupFiles(appDir({ 'src/startup/pick-version.prompt.ts': source }))[0]?.content ?? '';
    expect(read("export default defineStartupPrompt({\n  order: 10,\n  async run(ctx) { await ctx.confirmAction({ title: 'Hi', message: 'There' }); },\n});\n"))
      .toContain(`prompt: lazyStartupPrompt({"order":10}, () => import('../src/startup/pick-version.prompt'))`);
    expect(read("export default defineStartupPrompt({ run: async (ctx) => { ctx.nav.home('x'); } });\n"))
      .toContain(`lazyStartupPrompt({}, () => import('../src/startup/pick-version.prompt'))`);
    expect(read("const prompt = defineStartupPrompt({ order: -1, run: async () => undefined });\nexport default prompt;\n")).toContain('lazyStartupPrompt({"order":-1}');
    expect(read('export default defineStartupPrompt({ order: FIRST, run: async () => undefined });\n')).toContain("import pickVersionPrompt from '../src/startup/pick-version.prompt';");
  });

  it('writes an empty list for an app with no src/startup, and skips files with no default export', () => {
    expect(renderStartupFiles(appDir({}))[0]?.content).toContain('startupPromptsFromFiles([])');
    const dir = appDir({ 'src/startup/welcome.prompt.ts': 'export default defineStartupPrompt({ run: async () => undefined });\n', 'src/startup/half.prompt.ts': 'const x = 1;\n' });
    expect(renderStartupFiles(dir)[0]?.content).toContain("{ id: 'welcome', prompt: lazyStartupPrompt(");
    expect(renderStartupFiles(dir)[0]?.content).not.toContain('half');
  });

  it('counts src/startup as a sync input, so a new prompt makes .brock stale', () => {
    expect(SYNC_INPUTS).toContain('src/startup');
  });
});

describe('checkStartup', () => {
  it('reports strays, folders, bad ids and missing default exports', () => {
    const dir = appDir({
      'src/startup/welcome.prompt.ts': 'export default defineStartupPrompt({ run: async () => undefined });\n',
      'src/startup/helpers.ts': 'export const y = 1;\n',
      'src/startup/parts/a.ts': '',
      'src/startup/Bad.prompt.ts': 'export default x;\n',
      'src/startup/empty.prompt.ts': 'const x = 1;\n',
    });
    const findings = checkStartup(dir).join('\n');
    expect(findings).toContain('src/startup/helpers.ts: not a start-up prompt file');
    expect(findings).toContain('src/startup/parts: src/startup holds prompt files and their constants files only');
    expect(findings).toContain('"Bad" is not a kebab-case id');
    expect(findings).toContain('src/startup/empty.prompt.ts: no default export');
    expect(findings).not.toContain('welcome.prompt.ts');
  });

  it('accepts the constants file lint asks for beside a prompt, and a shared one, but nothing else', () => {
    const dir = appDir({
      'src/startup/welcome.prompt.ts': 'export default defineStartupPrompt({ run: async () => undefined });\n',
      'src/startup/welcome.prompt.constants.ts': "const KEY = 'a';\nexport { KEY };\n",
      'src/startup/shared.constants.ts': "const KEY = 'b';\nexport { KEY };\n",
      'src/startup/welcome.prompt.type.ts': '',
    });
    expect(checkStartup(dir)).toHaveLength(1);
    expect(checkStartup(dir)[0]).toContain('src/startup/welcome.prompt.type.ts: not a start-up prompt file');
    expect(renderStartupFiles(dir)[0]?.content).not.toContain('constants');
  });
});

describe('startup-prompts migration (0.80.0)', () => {
  it('adds startupPrompts={appStartupPrompts} and its import to src/main.tsx, once', () => {
    const once = migration.apply({ path: 'src/main.tsx', source: MAIN });
    expect(once.source).toContain("import { appTours } from '../.brock/tours';\nimport { appStartupPrompts } from '../.brock/startup';");
    expect(once.source).toContain('      tours={appTours}\n      startupPrompts={appStartupPrompts}\n    />');
    expect(migration.apply({ path: 'src/main.tsx', source: once.source }).source).toBe(once.source);
  });

  it('leaves a main.tsx that already passes startupPrompts alone, and any other file', () => {
    const wired = MAIN.replace('      tours={appTours}\n', '      tours={appTours}\n      startupPrompts={mine}\n');
    expect(migration.apply({ path: 'src/main.tsx', source: wired }).source).toBe(wired);
    expect(migration.apply({ path: 'src/other.tsx', source: MAIN }).source).toBe(MAIN);
  });
});

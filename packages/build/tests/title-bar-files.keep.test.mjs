/* @layer tooling-scripts @kind test */
import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { afterEach, describe, expect, it } from 'vitest';
import { migration } from '../migrations/0.17.0/title-bar-files.mjs';
import { checkTitleBar } from '../src/title-bar/check-title-bar.mjs';
import { renderTitleBar, renderTitleBarFiles } from '../src/title-bar/render-title-bar.mjs';

const MAIN = [
  "import { BrockApp } from '@drizztdourden08/brock-react';",
  "import { screenTree } from '../.brock/screens';",
  "import { appWidgets } from '../.brock/widgets';",
  '',
  'createRoot(root).render(',
  '  <StrictMode>',
  '    <BrockApp<AppSettings>',
  '      product={product}',
  '      screenTree={screenTree}',
  '      widgets={appWidgets}',
  '    />',
  '  </StrictMode>,',
  ');',
  '',
].join('\n');

const dirs = [];

const appDir = (files) => {
  const dir = mkdtempSync(join(tmpdir(), 'brock-title-bar-'));
  dirs.push(dir);
  writeFileSync(join(dir, 'brock.config.ts'), 'export default {};\n');
  for (const [path, content] of Object.entries(files)) {
    mkdirSync(join(dir, path, '..'), { recursive: true });
    writeFileSync(join(dir, path), content);
  }
  return dir;
};

afterEach(() => {
  for (const dir of dirs.splice(0)) rmSync(dir, { recursive: true, force: true });
});

describe('renderTitleBar', () => {
  it('imports each item file into one list keyed by the file id', () => {
    expect(renderTitleBar([{ id: 'room-status', path: 'src/title-bar/room-status.action.ts' }])).toBe([
      '// generated by brock sync, do not edit',
      "import { titleBarFromFiles } from '@drizztdourden08/brock-react';",
      "import roomStatusItem from '../src/title-bar/room-status.action';",
      '',
      'const appTitleBar = titleBarFromFiles([',
      "  { id: 'room-status', source: roomStatusItem },",
      ']);',
      '',
      'export { appTitleBar };',
      '',
    ].join('\n'));
  });

  it('writes an empty list for an app with no src/title-bar, and skips files with no default export', () => {
    expect(renderTitleBarFiles(appDir({}))[0]?.content).toContain('titleBarFromFiles([])');
    const dir = appDir({ 'src/title-bar/rooms.action.ts': 'export default defineTitleBarItem({});\n', 'src/title-bar/half.action.ts': 'const x = 1;\n' });
    expect(renderTitleBarFiles(dir)[0]?.content).toContain("{ id: 'rooms', source: roomsItem }");
    expect(renderTitleBarFiles(dir)[0]?.content).not.toContain('half');
  });
});

describe('checkTitleBar', () => {
  it('reports strays, folders, bad ids, missing default exports and standard ids', () => {
    const dir = appDir({
      'src/title-bar/rooms.action.ts': 'export default x;\n',
      'src/title-bar/helpers.ts': 'export const y = 1;\n',
      'src/title-bar/parts/a.ts': '',
      'src/title-bar/Bad.action.ts': 'export default x;\n',
      'src/title-bar/empty.action.ts': 'const x = 1;\n',
      'src/title-bar/search.action.ts': 'export default x;\n',
    });
    const findings = checkTitleBar(dir).join('\n');
    expect(findings).toContain('src/title-bar/helpers.ts: not a title bar item file');
    expect(findings).toContain('src/title-bar/parts: src/title-bar holds title bar item files and their constants files only');
    expect(findings).toContain('"Bad" is not a kebab-case id');
    expect(findings).toContain('src/title-bar/empty.action.ts: no default export');
    expect(findings).toContain('"search" is a standard Brock title bar item id');
    expect(findings).not.toContain('rooms.action.ts');
  });
});

describe('title-bar-files migration', () => {
  it('adds titleBar={appTitleBar} and its import to src/main.tsx, once', () => {
    const once = migration.apply({ path: 'src/main.tsx', source: MAIN });
    expect(once.source).toContain("import { appWidgets } from '../.brock/widgets';\nimport { appTitleBar } from '../.brock/title-bar';");
    expect(once.source).toContain('      widgets={appWidgets}\n      titleBar={appTitleBar}\n    />');
    expect(migration.apply({ path: 'src/main.tsx', source: once.source }).source).toBe(once.source);
  });

  it('turns titleBarActions in an app module into a to-do and leaves other files alone', () => {
    const source = "const hosting = { id: 'hosting', titleBarActions: [useRoomAction] };\n";
    const result = migration.apply({ path: 'src/modules/hosting/renderer.ts', source });
    expect(result.source).toBe(source);
    expect(result.todos).toHaveLength(1);
    expect(result.todos[0]?.message).toContain('src/title-bar/<id>.action.ts');
  });
});

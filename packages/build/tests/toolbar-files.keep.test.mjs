/* @layer tooling-scripts @kind test */
import { afterEach, describe, expect, it } from 'vitest';
import { collectFindings } from '@drizztdourden08/standards/structure';
import brockApp from '../standards.extension.mjs';
import { migration } from '../migrations/0.86.0/toolbar-files.mjs';
import { SYNC_INPUTS } from '../src/freshness/freshness.constants.mjs';
import { checkToolbars } from '../src/toolbars/check-toolbars.mjs';
import { renderToolbars, renderToolbarsFiles } from '../src/toolbars/render-toolbars.mjs';
import { appDirs } from './app-dir-harness.mjs';

const MAIN = [
  "import { BrockApp } from '@drizztdourden08/brock-react';",
  "import { screenTree } from '../.brock/screens';",
  "import { appTours } from '../.brock/tours';",
  '',
  'createRoot(root).render(',
  '  <StrictMode>',
  '    <BrockApp<AppSettings>',
  '      product={product}',
  '      tours={appTours}',
  '    />',
  '  </StrictMode>,',
  ');',
  '',
].join('\n');

const TOOLBAR = "export default defineToolbar({ id: 'drawing-tools', label: 'Drawing tools', defaultSide: 'left', render: (slot) => null });\n";

const { appDir, cleanUp } = appDirs('brock-toolbars-');

afterEach(cleanUp);

describe('renderToolbars', () => {
  it('imports each toolbar file into one typed list', () => {
    expect(renderToolbars([{ id: 'drawing-tools', path: 'src/toolbars/drawing-tools.toolbar.tsx' }, { id: 'zoom', path: 'src/toolbars/zoom.toolbar.tsx' }])).toBe([
      '// generated by brock sync, do not edit',
      "import type { ToolbarDef } from '@drizztdourden08/brock-react';",
      "import drawingToolsToolbar from '../src/toolbars/drawing-tools.toolbar';",
      "import zoomToolbar from '../src/toolbars/zoom.toolbar';",
      '',
      'const appToolbars: ToolbarDef[] = [',
      '  drawingToolsToolbar,',
      '  zoomToolbar,',
      '];',
      '',
      'export { appToolbars };',
      '',
    ].join('\n'));
  });

  it('writes an empty list for an app with no src/toolbars, and skips files with no default export', () => {
    expect(renderToolbarsFiles(appDir({}))).toEqual([{ path: '.brock/toolbars.ts', content: renderToolbars([]) }]);
    expect(renderToolbars([])).toContain('const appToolbars: ToolbarDef[] = [];');
    const dir = appDir({ 'src/toolbars/drawing-tools.toolbar.tsx': TOOLBAR, 'src/toolbars/half.toolbar.tsx': 'const x = 1;\n' });
    expect(renderToolbarsFiles(dir)[0]?.content).toContain("import drawingToolsToolbar from '../src/toolbars/drawing-tools.toolbar';");
    expect(renderToolbarsFiles(dir)[0]?.content).not.toContain('half');
  });

  it('counts src/toolbars as a sync input, so a new toolbar makes .brock stale', () => {
    expect(SYNC_INPUTS).toContain('src/toolbars');
  });
});

describe('checkToolbars', () => {
  it('accepts a toolbar file with its constants file', () => {
    const dir = appDir({
      'src/toolbars/drawing-tools.toolbar.tsx': TOOLBAR,
      'src/toolbars/drawing-tools.toolbar.constants.ts': 'export const A = 1;\n',
      'src/toolbars/shared.constants.ts': 'export const B = 1;\n',
    });
    expect(checkToolbars(dir)).toEqual([]);
  });

  it('reports strays, folders, bad ids, missing default exports and an id that differs from the file name', () => {
    const dir = appDir({
      'src/toolbars/drawing-tools.toolbar.tsx': TOOLBAR,
      'src/toolbars/helpers.ts': 'export const y = 1;\n',
      'src/toolbars/parts/a.ts': '',
      'src/toolbars/Bad.toolbar.tsx': 'export default x;\n',
      'src/toolbars/empty.toolbar.tsx': 'const x = 1;\n',
      'src/toolbars/zoom.toolbar.tsx': "export default defineToolbar({ id: 'zoomer', label: 'Zoom', defaultSide: 'top', render: () => null });\n",
    });
    const findings = checkToolbars(dir).join('\n');
    expect(findings).toContain('src/toolbars/helpers.ts: not a toolbar file');
    expect(findings).toContain('src/toolbars/parts: src/toolbars holds toolbar files and their constants files only');
    expect(findings).toContain('"Bad" is not a kebab-case id');
    expect(findings).toContain('src/toolbars/empty.toolbar.tsx: no default export');
    expect(findings).toContain('defineToolbar names id "zoomer", but the file name makes it "zoom"');
    expect(findings).not.toContain('drawing-tools.toolbar.tsx');
  });
});

describe('the brock-app extension on src/toolbars', () => {
  it('holds the folder to toolbar files with a default export and their constants', async () => {
    const files = { 'package.json': '{ "name": "app" }', 'src/main.tsx': '' };
    const ok = appDir({ ...files, 'src/toolbars/drawing-tools.toolbar.tsx': TOOLBAR, 'src/toolbars/drawing-tools.toolbar.constants.ts': 'export const A = 1;\n' });
    expect((await collectFindings(ok, '@app', [brockApp])).findings).toEqual([]);
    const bad = appDir({ ...files, 'src/toolbars/drawing-tools.toolbar.tsx': TOOLBAR, 'src/toolbars/helpers.ts': '', 'src/toolbars/none.toolbar.tsx': 'const x = 1;\n' });
    const { findings } = await collectFindings(bad, '@app', [brockApp]);
    expect(findings.map((finding) => finding.split(': ')[0]).sort()).toEqual(['src/toolbars/helpers.ts', 'src/toolbars/none.toolbar.tsx']);
  });
});

describe('toolbar-files migration (0.86.0)', () => {
  it('adds toolbars={appToolbars} and its import to src/main.tsx, once', () => {
    const once = migration.apply({ path: 'src/main.tsx', source: MAIN });
    expect(once.source).toContain("import { appTours } from '../.brock/tours';\nimport { appToolbars } from '../.brock/toolbars';");
    expect(once.source).toContain('      tours={appTours}\n      toolbars={appToolbars}\n    />');
    expect(migration.apply({ path: 'src/main.tsx', source: once.source }).source).toBe(once.source);
  });

  it('leaves a main.tsx that already passes toolbars alone, and any other file', () => {
    const wired = MAIN.replace('      tours={appTours}\n', '      tours={appTours}\n      toolbars={mine}\n');
    expect(migration.apply({ path: 'src/main.tsx', source: wired }).source).toBe(wired);
    expect(migration.apply({ path: 'src/other.tsx', source: MAIN }).source).toBe(MAIN);
  });
});

/* @layer tooling-scripts @kind test */
import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { afterEach, describe, expect, it } from 'vitest';
import { migration } from '../migrations/0.27.0/tour-files.mjs';
import { SYNC_INPUTS } from '../src/freshness/freshness.constants.mjs';
import { checkTours } from '../src/tours/check-tours.mjs';
import { renderTours, renderToursFiles } from '../src/tours/render-tours.mjs';

const MAIN = [
  "import { BrockApp } from '@drizztdourden08/brock-react';",
  "import { screenTree } from '../.brock/screens';",
  "import { appTitleBar } from '../.brock/title-bar';",
  '',
  'createRoot(root).render(',
  '  <StrictMode>',
  '    <BrockApp<AppSettings>',
  '      product={product}',
  '      screenTree={screenTree}',
  '      titleBar={appTitleBar}',
  '    />',
  '  </StrictMode>,',
  ');',
  '',
].join('\n');

const made = new Set();

const writeInto = (dir) => ([path, content]) => {
  const target = join(dir, path);
  mkdirSync(dirname(target), { recursive: true });
  writeFileSync(target, content);
};

const appDir = (files) => {
  const dir = mkdtempSync(join(tmpdir(), 'brock-tours-'));
  made.add(dir);
  Object.entries({ 'brock.config.ts': 'export default {};\n', ...files }).forEach(writeInto(dir));
  return dir;
};

afterEach(() => {
  made.forEach((dir) => rmSync(dir, { recursive: true, force: true }));
  made.clear();
});

describe('renderTours', () => {
  it('imports each tour file into one list keyed by the file id', () => {
    expect(renderTours([{ id: 'first-steps', path: 'src/tours/first-steps.tour.ts' }])).toBe([
      '// generated by brock sync, do not edit',
      "import { toursFromFiles } from '@drizztdourden08/brock-react';",
      "import firstStepsTour from '../src/tours/first-steps.tour';",
      '',
      'const appTours = toursFromFiles([',
      "  { id: 'first-steps', tour: firstStepsTour },",
      ']);',
      '',
      'export { appTours };',
      '',
    ].join('\n'));
  });

  it('writes an empty list for an app with no src/tours, and skips files with no default export', () => {
    expect(renderToursFiles(appDir({}))[0]?.content).toContain('toursFromFiles([])');
    const dir = appDir({ 'src/tours/welcome.tour.ts': "export default defineTour({ id: 'welcome' });\n", 'src/tours/half.tour.ts': 'const x = 1;\n' });
    expect(renderToursFiles(dir)[0]?.content).toContain("{ id: 'welcome', tour: welcomeTour }");
    expect(renderToursFiles(dir)[0]?.content).not.toContain('half');
  });

  it('counts src/tours as a sync input, so a new tour makes .brock stale', () => {
    expect(SYNC_INPUTS).toContain('src/tours');
  });
});

describe('checkTours', () => {
  it('reports strays, folders, bad ids, missing default exports and an id that differs from the file name', () => {
    const dir = appDir({
      'src/tours/welcome.tour.ts': "export default defineTour({ id: 'welcome', title: 'Welcome', steps: [] });\n",
      'src/tours/helpers.ts': 'export const y = 1;\n',
      'src/tours/parts/a.ts': '',
      'src/tours/Bad.tour.ts': 'export default x;\n',
      'src/tours/empty.tour.ts': 'const x = 1;\n',
      'src/tours/sessions.tour.ts': "export default defineTour({ id: 'session', title: 'S', steps: [] });\n",
    });
    const findings = checkTours(dir).join('\n');
    expect(findings).toContain('src/tours/helpers.ts: not a tour file');
    expect(findings).toContain('src/tours/parts: src/tours holds tour files only');
    expect(findings).toContain('"Bad" is not a kebab-case id');
    expect(findings).toContain('src/tours/empty.tour.ts: no default export');
    expect(findings).toContain('defineTour names id "session", but the file name makes it "sessions"');
    expect(findings).not.toContain('welcome.tour.ts');
  });
});

describe('tour-files migration (0.27.0)', () => {
  it('adds tours={appTours} and its import to src/main.tsx, once', () => {
    const once = migration.apply({ path: 'src/main.tsx', source: MAIN });
    expect(once.source).toContain("import { appTitleBar } from '../.brock/title-bar';\nimport { appTours } from '../.brock/tours';");
    expect(once.source).toContain('      titleBar={appTitleBar}\n      tours={appTours}\n    />');
    expect(migration.apply({ path: 'src/main.tsx', source: once.source }).source).toBe(once.source);
  });

  it('leaves a main.tsx that already passes tours alone', () => {
    const wired = MAIN.replace('      titleBar={appTitleBar}\n', '      titleBar={appTitleBar}\n      tours={myTours}\n');
    expect(migration.apply({ path: 'src/main.tsx', source: wired }).source).toBe(wired);
  });
});

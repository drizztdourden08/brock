/* @layer tooling-scripts @kind test */
import { afterEach, describe, expect, it } from 'vitest';
import { checkTours } from '../src/tours/check-tours.mjs';
import { renderTours, renderToursFiles } from '../src/tours/render-tours.mjs';
import { appDirs } from './app-dir-harness.mjs';

const { appDir, cleanUp } = appDirs('brock-tours-');

afterEach(cleanUp);

describe('K1 renderTours', { tags: ['critical'] }, () => {
  it('lists a tour whose title, description and trigger are literals by those alone, and loads its steps when it starts', () => {
    const shell = { title: 'Welcome', description: 'A walk', trigger: 'first-run' };
    expect(renderTours([{ id: 'welcome', path: 'src/tours/welcome.tour.ts', shell }])).toBe([
      '// generated by brock sync, do not edit',
      "import { lazyTour, toursFromFiles } from '@drizztdourden08/brock-react';",
      '',
      'const appTours = toursFromFiles([',
      `  { id: 'welcome', tour: lazyTour(${JSON.stringify(shell)}, () => import('../src/tours/welcome.tour')) },`,
      ']);',
      '',
      'export { appTours };',
      '',
    ].join('\n'));
    const read = (source) => renderToursFiles(appDir({ 'src/tours/welcome.tour.ts': source }))[0]?.content ?? '';
    expect(read("export default defineTour({\n  id: 'welcome',\n  title: 'Welcome',\n  trigger: 'first-run',\n  steps: [{ id: 'a', title: 'A', body: hint('a'), before: async () => { await openIt(); } }],\n});\n"))
      .toContain(`lazyTour({"title":"Welcome","trigger":"first-run"}, () => import('../src/tours/welcome.tour'))`);
    expect(read("const tour = defineTour({ id: 'welcome', title: 'Welcome', steps: [] });\nexport default tour;\n")).toContain('lazyTour({"title":"Welcome"}');
    expect(read("export default defineTour({ id: 'welcome', title: WELCOME_TITLE, steps: [] });\n")).toContain("import welcomeTour from '../src/tours/welcome.tour';");
  });

  it('writes an empty list for an app with no src/tours, and skips files with no default export', () => {
    expect(renderToursFiles(appDir({}))[0]?.content).toContain('toursFromFiles([])');
    const dir = appDir({ 'src/tours/welcome.tour.ts': "export default defineTour({ id: 'welcome' });\n", 'src/tours/half.tour.ts': 'const x = 1;\n' });
    expect(renderToursFiles(dir)[0]?.content).toContain("{ id: 'welcome', tour: welcomeTour }");
    expect(renderToursFiles(dir)[0]?.content).not.toContain('half');
  });
});

describe('K1 checkTours', { tags: ['critical'] }, () => {
  it('reports strays, folders, bad ids, missing default exports and an id that differs from the file name', () => {
    const dir = appDir({
      'src/tours/welcome.tour.ts': "export default defineTour({ id: 'welcome', title: 'Welcome', steps: [] });\n",
      'src/tours/helpers.ts': 'export const y = 1;\n',
      'src/tours/parts/a.ts': '',
      'src/tours/Bad.tour.ts': 'export default x;\n',
      'src/tours/empty.tour.ts': 'const x = 1;\n',
      'src/tours/sessions.tour.ts': "export default defineTour({ id: 'session', title: 'S', steps: [] });\n",
    });
    const findings = checkTours(dir).join('\n');
    expect(findings).toContain('src/tours/helpers.ts: not a tour file');
    expect(findings).toContain('src/tours/parts: src/tours holds tour files and their constants files only');
    expect(findings).toContain('"Bad" is not a kebab-case id');
    expect(findings).toContain('src/tours/empty.tour.ts: no default export');
    expect(findings).toContain('defineTour names id "session", but the file name makes it "sessions"');
    expect(findings).not.toContain('welcome.tour.ts');
  });

  it('accepts the constants file lint asks for beside a tour, and a shared one, but nothing else', () => {
    const dir = appDir({
      'src/tours/welcome.tour.ts': "import { NEW_PRESET } from './welcome.tour.constants';\nexport default defineTour({ id: 'welcome', title: 'Welcome', steps: [] });\n",
      'src/tours/welcome.tour.constants.ts': "const NEW_PRESET = '.presets button';\nexport { NEW_PRESET };\n",
      'src/tours/tour-targets.constants.ts': "const MENU = '.menu';\nexport { MENU };\n",
      'src/tours/Targets.constants.ts': '',
      'src/tours/welcome.tour.type.ts': '',
    });
    expect(checkTours(dir)).toEqual([
      'src/tours/Targets.constants.ts: not a tour file; a tour is src/tours/<id>.tour.ts, default-exporting defineTour({ id, title, steps, trigger? }); a tour\'s constants go beside it in <id>.tour.constants.ts (or <name>.constants.ts when several tours share them), and shared step helpers in src/hooks or src/stores',
      'src/tours/welcome.tour.type.ts: not a tour file; a tour is src/tours/<id>.tour.ts, default-exporting defineTour({ id, title, steps, trigger? }); a tour\'s constants go beside it in <id>.tour.constants.ts (or <name>.constants.ts when several tours share them), and shared step helpers in src/hooks or src/stores',
    ]);
    expect(renderToursFiles(dir)[0]?.content).toContain(`{ id: 'welcome', tour: lazyTour({"title":"Welcome"}, () => import('../src/tours/welcome.tour')) }`);
    expect(renderToursFiles(dir)[0]?.content).not.toContain('constants');
  });
});

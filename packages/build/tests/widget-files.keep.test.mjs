/* @layer tooling-scripts @kind test */
import { describe, expect, it } from 'vitest';
import { migration } from '../migrations/0.11.0/widget-files.mjs';
import { renderWidgets } from '../src/widgets/render-widgets.mjs';

const MAIN = [
  "import { BrockApp, registerWidgets } from '@drizztdourden08/brock-react';",
  "import { rendererBootTasks } from '../.brock/boot.renderer';",
  "import { screenTree } from '../.brock/screens';",
  "import { SESSION_WIDGETS } from './widgets/session-widgets.constants';",
  '',
  'registerWidgets(SESSION_WIDGETS);',
  '',
  'createRoot(root).render(',
  '  <StrictMode>',
  '    <BrockApp<AppSettings>',
  '      product={product}',
  '      screenTree={screenTree}',
  '      bootTasks={rendererBootTasks}',
  '    />',
  '  </StrictMode>,',
  ');',
  '',
].join('\n');

const FACTORY = [
  "import { defineWidget } from '@drizztdourden08/brock-react';",
  '',
  'const sessionWidget = (input) => defineWidget({ ...input, popOut: true });',
  "const clock = defineWidget({ id: 'clock', label: 'Clock', render: () => null });",
  '',
].join('\n');

const run = (path, source) => migration.apply({ path, source });

describe('renderWidgets', () => {
  it('imports each widget file and its meta into one list', () => {
    expect(renderWidgets([
      { id: 'live-room', path: 'src/widgets/live-room.widget.tsx', hasMeta: true },
      { id: 'notes', path: 'src/widgets/notes.widget.tsx', hasMeta: false },
    ])).toBe([
      '// generated by brock sync, do not edit',
      "import { widgetsFromFiles } from '@drizztdourden08/brock-react';",
      "import LiveRoomWidget, { meta as liveRoomWidgetMeta } from '../src/widgets/live-room.widget';",
      "import NotesWidget from '../src/widgets/notes.widget';",
      '',
      'const appWidgets = widgetsFromFiles([',
      "  { id: 'live-room', component: LiveRoomWidget, meta: liveRoomWidgetMeta },",
      "  { id: 'notes', component: NotesWidget },",
      ']);',
      'const appWidgetLayout = undefined;',
      '',
      'export { appWidgetLayout, appWidgets };',
      '',
    ].join('\n'));
  });

  it('imports src/widgets/layout.ts as the app widget layout when there is one', () => {
    const source = renderWidgets([], { path: 'src/widgets/layout.ts' });
    expect(source).toContain("import appWidgetLayout from '../src/widgets/layout';");
    expect(source).not.toContain('const appWidgetLayout');
    expect(source).toContain('export { appWidgetLayout, appWidgets };');
  });

  it('writes an empty list when the app has no widget files', () => {
    expect(renderWidgets([])).toContain('const appWidgets = widgetsFromFiles([]);');
  });
});

describe('the widget-files migration', () => {
  it('wires .brock/widgets into src/main.tsx and flags registerWidgets', () => {
    const { source, todos } = run('src/main.tsx', MAIN);
    expect(source).toContain("import { screenTree } from '../.brock/screens';\nimport { appWidgets } from '../.brock/widgets';\n");
    expect(source).toContain('      bootTasks={rendererBootTasks}\n      widgets={appWidgets}\n    />');
    expect(todos.map((todo) => todo.line)).toEqual([7]);
    expect(todos[0]?.message).toContain('registerWidgets');
  });

  it('changes nothing on a second run', () => {
    const once = run('src/main.tsx', MAIN).source;
    expect(run('src/main.tsx', once).source).toBe(once);
  });

  it('turns each hand definition into a to-do naming its file', () => {
    const { source, todos } = run('src/widgets/session-widget.ts', FACTORY);
    expect(source).toBe(FACTORY);
    expect(todos.map((todo) => todo.line)).toEqual([3, 4]);
    expect(todos[0]?.message).toContain('src/widgets/<id>.widget.tsx');
    expect(todos[1]?.message).toContain('src/widgets/clock.widget.tsx');
  });

  it('flags a widgets prop passed by hand but not the generated one', () => {
    const hand = 'const app = <BrockApp product={product} widgets={MY_WIDGETS} />;\n';
    expect(run('src/app.tsx', hand).todos).toHaveLength(1);
    expect(run('src/app.tsx', hand.replace('MY_WIDGETS', 'appWidgets')).todos).toEqual([]);
  });

  it('leaves widget files alone', () => {
    expect(run('src/widgets/clock.widget.tsx', FACTORY)).toEqual({ source: FACTORY, todos: [] });
  });
});

/* @layer tooling-scripts @kind test */
import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { afterEach, describe, expect, it } from 'vitest';
import { migration } from '../migrations/0.53.0/widget-kits-prop.mjs';
import { checkWidgets } from '../src/widgets/check-widgets.mjs';
import { renderWidgetKits } from '../src/widgets/render-widget-kits.mjs';
import { renderWidgetsFiles } from '../src/widgets/render-widgets.mjs';

const made = [];

const appWith = (files) => {
  const root = mkdtempSync(join(tmpdir(), 'brock-widget-kits-'));
  for (const [file, text] of Object.entries(files)) {
    const path = join(root, file);
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, text);
  }
  made.push(root);
  return root;
};

const KIT = "const kit = { label: 'Shadow editor', devOnly: true, requires: { context: 'game', reason: 'Start the game first.' } };\n\nexport default kit;\n";
const MEMBER = "const Tree = () => null;\n\nconst meta = { kit: 'shadow' };\n\nexport default Tree;\nexport { meta };\n";
const OVERLAY = "const Gizmo = () => null;\n\nconst meta = { kit: 'shadow', label: 'Gizmo' };\n\nexport default Gizmo;\nexport { meta };\n";

const MAIN = "import { appWidgetLayout, appWidgets } from '../.brock/widgets';\n\nconst app = (\n  <BrockApp\n    widgets={appWidgets}\n    widgetLayout={appWidgetLayout}\n  />\n);\n";

afterEach(() => {
  for (const root of made.splice(0)) rmSync(root, { recursive: true, force: true });
});

describe('renderWidgetKits', () => {
  it('imports each kit file and each overlay meta, and loads each overlay on first draw', () => {
    expect(renderWidgetKits([{ id: 'shadow', path: 'src/widgets/shadow.kit.ts' }], [{ id: 'shadow-gizmo', path: 'src/widgets/shadow-gizmo.overlay.tsx' }])).toBe([
      '// generated by brock sync, do not edit',
      "import { lazyComponent, widgetKitsFromFiles } from '@drizztdourden08/brock-react';",
      "import shadowKit from '../src/widgets/shadow.kit';",
      "import { meta as shadowGizmoOverlayMeta } from '../src/widgets/shadow-gizmo.overlay';",
      '',
      'const appWidgetKits = widgetKitsFromFiles({',
      '  kits: [',
      "    { id: 'shadow', meta: shadowKit },",
      '  ],',
      '  overlays: [',
      "    { id: 'shadow-gizmo', component: lazyComponent(() => import('../src/widgets/shadow-gizmo.overlay')), meta: shadowGizmoOverlayMeta },",
      '  ],',
      '});',
      '',
      'export { appWidgetKits };',
      '',
    ].join('\n'));
  });

  it('writes .brock/widget-kits.ts for every app, empty without kits', () => {
    const files = renderWidgetsFiles(appWith({ 'package.json': '{}' }));
    expect(files.map((file) => file.path)).toEqual(['.brock/widgets.ts', '.brock/widget-kits.ts']);
    expect(files[1]?.content).toContain('  kits: [],\n  overlays: [],');
  });
});

describe('kit files in src/widgets', () => {
  it('accepts a kit, its overlay and a widget that joins it, and lists the member with the widgets', () => {
    const root = appWith({ 'src/widgets/shadow.kit.ts': KIT, 'src/widgets/shadow-tree.widget.tsx': MEMBER, 'src/widgets/shadow-gizmo.overlay.tsx': OVERLAY, 'src/widgets/shadow.kit.constants.ts': 'export const A = 1;\n' });
    expect(checkWidgets(root)).toEqual([]);
    const [widgets, kits] = renderWidgetsFiles(root);
    expect(widgets?.content).toContain("id: 'shadow-tree'");
    expect(kits?.content).toContain("{ id: 'shadow', meta: shadowKit }");
    expect(kits?.content).toContain("id: 'shadow-gizmo'");
  });

  it('reports a kit without a default export, an unknown kit field, an overlay without meta and a widget naming a missing kit', () => {
    const root = appWith({
      'src/widgets/broken.kit.ts': 'export const kit = {};\n',
      'src/widgets/odd.kit.ts': "const kit = { label: 'Odd', colour: 'red' };\n\nexport default kit;\n",
      'src/widgets/loose.overlay.tsx': 'const Loose = () => null;\n\nexport default Loose;\n',
      'src/widgets/lost.widget.tsx': MEMBER,
    });
    expect(checkWidgets(root)).toEqual([
      'src/widgets/lost.widget.tsx: meta.kit names "shadow", but there is no src/widgets/shadow.kit.ts',
      'src/widgets/broken.kit.ts: no default export; a kit file default-exports its WidgetKitMeta ({ label, icon, devOnly, requires, layout })',
      'src/widgets/odd.kit.ts: kit.colour is not a kit field (label, icon, order, devOnly, requires, layout)',
      'src/widgets/loose.overlay.tsx: no meta; an overlay exports meta = { kit } naming the kit it belongs to',
    ]);
  });
});

describe('the widget-kits-prop migration', () => {
  it('wires .brock/widget-kits into src/main.tsx once', () => {
    const once = migration.apply({ path: 'src/main.tsx', source: MAIN }).source;
    expect(once).toContain("import { appWidgetLayout, appWidgets } from '../.brock/widgets';\nimport { appWidgetKits } from '../.brock/widget-kits';\n");
    expect(once).toContain('    widgetLayout={appWidgetLayout}\n    widgetKits={appWidgetKits}\n  />');
    expect(migration.apply({ path: 'src/main.tsx', source: once }).source).toBe(once);
  });

  it('leaves every other file alone', () => {
    expect(migration.apply({ path: 'src/app.tsx', source: MAIN })).toEqual({ source: MAIN, todos: [] });
  });
});

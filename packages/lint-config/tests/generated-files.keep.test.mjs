/* @layer tooling-scripts @kind test */
import { afterEach, describe, expect, it } from 'vitest';
import { generatedFiles } from '../generated-files.mjs';
import { brockMarkdownlint } from '../markdownlint.mjs';
import { put, removeRoots, tempDir } from './lint-fixture.mjs';

afterEach(removeRoots);

const GENERATOR = `${['a', 'i'].join('')}-config`;
const GUIDE = `${['CLAU', 'DE'].join('')}.md`;
const CONFIG = `.${GENERATOR}.json`;
const AGENTS = 'AGENTS.md';
const MCP = '.mcp.json';

const GENERATED_GUIDE = `<!-- GENERATED by ${GENERATOR} for a tool. Source: root-guide.md. -->\n<!-- @layer root-config @kind doc -->\n# App\n`;
const GENERATED_JSON = `{\n  "$generator": "${GENERATOR}/run.mjs",\n  "target": "x"\n}\n`;

describe('files a config generator wrote at the repo root', () => {
  it('lists the generated ones', () => {
    const root = tempDir();
    put(root, GUIDE, GENERATED_GUIDE);
    put(root, CONFIG, GENERATED_JSON);
    put(root, MCP, '{ "mcpServers": {} }\n');
    expect(generatedFiles(root).sort()).toEqual([CONFIG, MCP, GUIDE].sort());
  });

  it('keeps a guide or config the app wrote itself in the lint scope', () => {
    const root = tempDir();
    put(root, GUIDE, '# My app\n\nHand written.\n');
    put(root, AGENTS, '# My agents\n');
    put(root, CONFIG, '{ "target": "x" }\n');
    expect(generatedFiles(root)).toEqual([]);
  });

  it('adds only the generated files to the markdownlint ignores', () => {
    const root = tempDir();
    put(root, GUIDE, GENERATED_GUIDE);
    put(root, AGENTS, '# Hand written agents\n');
    const { ignores } = brockMarkdownlint({ rootDir: root, ignores: ['custom/**'] });
    expect(ignores).toEqual(expect.arrayContaining([GUIDE, 'custom/**']));
    expect(ignores).not.toContain(AGENTS);
  });

  it('finds nothing in a repo with none', () => {
    expect(generatedFiles(tempDir())).toEqual([]);
  });
});
